/**
 * Keeps the modules in `src/modules` apart from the core and from each other, so that deleting a
 * module's folder breaks nothing else (see "Modules" in AGENTS.md):
 *
 * - nothing outside `src/modules` imports a module, except the registries `scripts/modules.ts`
 *   generates (`*.gen.ts`) and the route stubs it writes in `src/routes`;
 * - a module imports another only through the other's `api/` folder, and only one it `requires` (or,
 *   for one it `enhances`, `api/extensions.ts` and types);
 * - a module changes only its own tables (`.insert()`, `.update()` and `.delete()` take its own
 *   tables): the other tables' owners offer services for that;
 * - a module's `module.ts`, which is in every tenant's bundle, imports statically only messages,
 *   icons, `#lib/modules/define`, types and its own small scripts: everything else is behind an
 *   `import()`.
 *
 * With no modules the checks pass on nothing, so they are also run on made-up files below, to show
 * they find what they should.
 */
import { existsSync, readdirSync, readFileSync } from "node:fs";
import { join, posix, relative } from "node:path";

import { describe, expect, test } from "vite-plus/test";

import { type ModuleGraph } from "#lib/modules/graph.ts";
import { moduleGraph } from "#lib/modules/ids.ts";

const root = join(import.meta.dirname, "../../../..");

interface SourceFile {
	/** Relative to the project root, with `/`. */
	path: string;
	source: string;
}

type ImportKind = "static" | "type" | "dynamic";

/** The modules a source file imports (`import`, `export … from`, `import()`), by kind. */
function importsOf(source: string): { specifier: string; kind: ImportKind }[] {
	const code = source.replace(/\/\*[\s\S]*?\*\//g, "").replace(/^\s*\/\/.*$/gm, "");
	const found: { specifier: string; kind: ImportKind }[] = [];
	const from = /\b(?:import|export)\s+(type\s+)?(?:[^"'`;]*?\sfrom\s+)?["']([^"']+)["']/g;
	for (const [, type, specifier] of code.matchAll(from)) {
		found.push({ specifier, kind: type ? "type" : "static" });
	}
	for (const [, specifier] of code.matchAll(/\bimport\(\s*["']([^"']+)["']\s*\)/g)) {
		found.push({ specifier, kind: "dynamic" });
	}
	return found;
}

/** The module (`src/modules/<id>`) that `specifier`, written in the file at `path`, points into. */
function targetOf(specifier: string, path: string): { id: string; rest: string } | undefined {
	if (specifier.startsWith("#modules/")) {
		const [, id, ...rest] = specifier.split("/");
		return { id, rest: rest.join("/") };
	}
	if (!specifier.startsWith(".")) return undefined;
	const target = /^src\/modules\/([^/]+)\/(.*)$/.exec(posix.join(posix.dirname(path), specifier));
	return target ? { id: target[1], rest: target[2] } : undefined;
}

const moduleOf = (specifier: string, path: string) => targetOf(specifier, path)?.id;

const isGenerated = (file: SourceFile) =>
	/^(?:\/\/|<!--) Generated by scripts\/modules\.ts/.test(file.source);

/** Imports of a module from files outside `src/modules` (other than the generated ones). */
export function outsideImports(files: SourceFile[]): string[] {
	return files.flatMap((file) =>
		file.path.startsWith("src/modules/") || isGenerated(file)
			? []
			: importsOf(file.source).flatMap(({ specifier }) =>
					moduleOf(specifier, file.path) ? [`${file.path} imports ${specifier}`] : [],
				),
	);
}

/**
 * Imports of one module by another that the rules don't allow: only a module's `api/` folder is
 * public, and only to modules that `require` it; one that only `enhances` it takes its
 * `api/extensions.ts` and types.
 */
export function apiImports(files: SourceFile[], graph: ModuleGraph): string[] {
	return files.flatMap((file) => {
		const own = /^src\/modules\/([^/]+)\//.exec(file.path)?.[1];
		if (!own) return [];
		return importsOf(file.source).flatMap(({ specifier, kind }) => {
			const target = targetOf(specifier, file.path);
			if (!target || target.id === own) return [];
			const problem = (why: string) => [`${file.path} imports ${specifier}: ${why}`];
			if (!target.rest.startsWith("api/")) return problem(`only ${target.id}'s api/ is public`);
			if (graph[own]?.requires.includes(target.id)) return [];
			if (graph[own]?.enhances.includes(target.id)) {
				return target.rest === "api/extensions.ts" || kind === "type"
					? []
					: problem(`${own} only enhances ${target.id}, so only its api/extensions.ts and types`);
			}
			return problem(`${own} doesn't require ${target.id}`);
		});
	});
}

/** The files a specifier written in the file at `path` points to, as a project path. */
const resolved = (specifier: string, path: string) =>
	specifier.startsWith("#lib/")
		? `src/lib/${specifier.slice("#lib/".length)}`
		: specifier.startsWith(".")
			? posix.join(posix.dirname(path), specifier)
			: specifier;

/** What a file imports by name: the local name of each binding, with where it comes from. */
function bindingsOf(file: SourceFile): Map<string, string> {
	const bindings = new Map<string, string>();
	const named =
		/\bimport\s+(?:type\s+)?(?:([\w$]+)\s*,?\s*)?(?:\{([^}]*)\}|\*\s+as\s+([\w$]+))?\s*from\s*["']([^"']+)["']/g;
	for (const [, whole, list = "", namespace, specifier] of file.source.matchAll(named)) {
		for (const local of [whole, namespace]) if (local) bindings.set(local, specifier);
		for (const part of list.split(",")) {
			const local = part
				.trim()
				.replace(/^type\s+/, "")
				.split(/\s+as\s+/)
				.pop();
			if (local) bindings.set(local, specifier);
		}
	}
	return bindings;
}

/**
 * Writes of a module to a table that isn't its own: `.insert(X)`, `.update(X)` or `.delete(X)`
 * where `X` comes from the core's schema or another module. The table's owner offers a service
 * for the change instead (e.g. `setOrdersStatus()`); reading its tables is fine.
 */
export function foreignWrites(files: SourceFile[], _graph: ModuleGraph): string[] {
	return files.flatMap((file) => {
		const own = /^src\/modules\/([^/]+)\//.exec(file.path)?.[1];
		if (!own) return [];
		const bindings = bindingsOf(file);
		return [
			...file.source.matchAll(/\.(?:insert|update|delete)\(\s*([\w$]+(?:\.[\w$]+)?)\s*\)/g),
		].flatMap(([, table]) => {
			const specifier = bindings.get(table.split(".")[0]);
			if (!specifier) return [];
			const from = resolved(specifier, file.path);
			const owner = moduleOf(specifier, file.path);
			return from === "src/lib/server/db/schema.ts" || (owner && owner !== own)
				? [`${file.path} writes ${table}, which isn't its own table: use its owner's service`]
				: [];
		});
	});
}

/** What a `module.ts` may import statically (types and `import()` loaders are free). */
const manifestImports = [
	/^#lib\/modules\/define\.ts$/,
	/^#lib\/paraglide\/messages\.js$/,
	/^@lucide\/svelte\/icons\/[\w-]+$/,
	// Its own small scripts, e.g. `./activity.ts`, `./labels.ts`; never components or remote functions.
	/^\.\/[\w.-]+\.ts$/,
];

/** Static imports in a `module.ts` that would pull more than the manifest into every bundle. */
export function heavyManifestImports(files: SourceFile[]): string[] {
	return files
		.filter((file) => /^src\/modules\/[^/]+\/module\.ts$/.test(file.path))
		.flatMap((file) =>
			importsOf(file.source).flatMap(({ specifier, kind }) =>
				kind !== "static" ||
				(manifestImports.some((allowed) => allowed.test(specifier)) &&
					!/\.remote\./.test(specifier))
					? []
					: [`${file.path} imports ${specifier} statically: load it with import()`],
			),
		);
}

describe("the checks", () => {
	const files: SourceFile[] = [
		{
			path: "src/lib/modules/manifests.gen.ts",
			source: `// Generated by scripts/modules.ts\nimport a from "#modules/a/module.ts";`,
		},
		{
			path: "src/routes/(app)/(modules)/a/+page.svelte",
			source: `<!-- Generated by scripts/modules.ts from x. -->\nimport R from "#modules/a/routes/(app)/+page.svelte";`,
		},
		{ path: "src/routes/(app)/orders/page.ts", source: `import { x } from "#modules/a/x.ts";` },
		{
			path: "src/lib/y.ts",
			source: `export { z } from "../modules/a/z.ts";\nconst v = await import("#modules/a/v.ts");`,
		},
		{
			path: "src/lib/ok.ts",
			source: `// import "#modules/a/commented.ts";\nimport { ok } from "./other.ts";`,
		},
		{
			path: "src/modules/a/module.ts",
			source: `
			import { defineModule } from "#lib/modules/define.ts";
						import Icon from "@lucide/svelte/icons/file-check";
			import type { Heavy } from "./heavy.svelte";
			import { subjects } from "./activity.ts";
			import Card from "./card.svelte";
			import { remote } from "./thing.remote.ts";
			import { server } from "#lib/server/db/index.ts";
			export default defineModule({ slots: { a: () => import("./card.svelte") } });
		`,
		},
	];

	test("find a module imported from outside, except by what the generator writes", () => {
		expect(outsideImports(files)).toEqual([
			`src/routes/(app)/orders/page.ts imports #modules/a/x.ts`,
			`src/lib/y.ts imports ../modules/a/z.ts`,
			`src/lib/y.ts imports #modules/a/v.ts`,
		]);
	});

	test("find heavy static imports in a manifest, and let the rest through", () => {
		expect(heavyManifestImports(files)).toEqual([
			`src/modules/a/module.ts imports ./card.svelte statically: load it with import()`,
			`src/modules/a/module.ts imports ./thing.remote.ts statically: load it with import()`,
			`src/modules/a/module.ts imports #lib/server/db/index.ts statically: load it with import()`,
		]);
	});
});

describe("the module rules", () => {
	const none = { requires: [], enhances: [], alwaysOn: false };
	const graph: ModuleGraph = {
		a: { requires: ["b"], enhances: ["c"], alwaysOn: false },
		b: none,
		c: none,
	};
	const file = (path: string, source: string): SourceFile => ({ path, source });

	test("let a module import the api of one it requires", () => {
		expect(
			apiImports([file("src/modules/a/x.ts", `import { y } from "#modules/b/api/y.ts";`)], graph),
		).toEqual([]);
		expect(
			apiImports([file("src/modules/a/x.ts", `import { y } from "../b/api/y.ts";`)], graph),
		).toEqual([]);
	});

	test("let a module import its own files however it likes", () => {
		expect(
			apiImports(
				[
					file(
						"src/modules/a/x.ts",
						`import { y } from "#modules/a/server/y.ts";\nimport "./z.ts";`,
					),
				],
				graph,
			),
		).toEqual([]);
	});

	test("find an import of anything but another module's api/", () => {
		expect(
			apiImports(
				[file("src/modules/a/x.ts", `import { y } from "#modules/b/server/y.ts";`)],
				graph,
			),
		).toEqual(["src/modules/a/x.ts imports #modules/b/server/y.ts: only b's api/ is public"]);
		expect(
			apiImports([file("src/modules/a/x.ts", `const y = await import("../b/y.ts");`)], graph),
		).toEqual(["src/modules/a/x.ts imports ../b/y.ts: only b's api/ is public"]);
	});

	test("let a module take the extension points and the types of one it enhances", () => {
		expect(
			apiImports(
				[file("src/modules/a/x.ts", `import { p } from "#modules/c/api/extensions.ts";`)],
				graph,
			),
		).toEqual([]);
		expect(
			apiImports(
				[file("src/modules/a/x.ts", `import type { Y } from "#modules/c/api/y.ts";`)],
				graph,
			),
		).toEqual([]);
		expect(
			apiImports([file("src/modules/a/x.ts", `import { y } from "#modules/c/api/y.ts";`)], graph),
		).toEqual([
			"src/modules/a/x.ts imports #modules/c/api/y.ts: a only enhances c, so only its api/extensions.ts and types",
		]);
	});

	test("find an import of a module that is neither required nor enhanced", () => {
		expect(
			apiImports([file("src/modules/b/x.ts", `import { y } from "#modules/a/api/y.ts";`)], graph),
		).toEqual(["src/modules/b/x.ts imports #modules/a/api/y.ts: b doesn't require a"]);
	});

	test("find a write to a table of the core or another module", () => {
		const core = `import { order } from "#lib/server/db/schema.ts";\nawait tx.update(order).set({})`;
		expect(foreignWrites([file("src/modules/a/x.ts", core)], graph)).toEqual([
			"src/modules/a/x.ts writes order, which isn't its own table: use its owner's service",
		]);
		const renamed = `import { order as o, type customer } from "../../lib/server/db/schema.ts";\nawait db.delete(o)`;
		expect(foreignWrites([file("src/modules/a/x.ts", renamed)], graph)).toEqual([
			"src/modules/a/x.ts writes o, which isn't its own table: use its owner's service",
		]);
		const other = `import * as b from "#modules/b/api/tables.ts";\nawait tx.insert(b.thing).values({})`;
		expect(foreignWrites([file("src/modules/a/x.ts", other)], graph)).toEqual([
			"src/modules/a/x.ts writes b.thing, which isn't its own table: use its owner's service",
		]);
	});

	test("let a module write its own tables, and read the core's", () => {
		const source = [
			`import { order, customer } from "#lib/server/db/schema.ts";`,
			`import { thing } from "./server/schema.ts";`,
			`import { other } from "#modules/a/server/schema.ts";`,
			`await tx.insert(thing).values({});`,
			`await tx.update(other).set({});`,
			`await tx.select().from(order).where(eq(customer.id, 1));`,
		].join("\n");
		expect(foreignWrites([file("src/modules/a/x.ts", source)], graph)).toEqual([]);
		expect(foreignWrites([file("src/lib/x.ts", source.replace("./server", "./x"))], graph)).toEqual(
			[],
		);
	});
});

