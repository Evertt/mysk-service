/**
 * Keeps the modules in `src/modules` apart from the core and from each other, so that deleting a
 * module's folder breaks nothing else (see "Modules" in AGENTS.md):
 *
 * - nothing outside `src/modules` imports a module, except the registries `scripts/modules.ts`
 *   generates (`*.gen.ts`) and the route stubs it writes in `src/routes`;
 * - a module imports no other module;
 * - a module's `module.ts`, which is in every tenant's bundle, imports statically only messages,
 *   icons, `#lib/modules/define`, types and its own small scripts: everything else is behind an
 *   `import()`.
 *
 * With no modules the checks pass on nothing, so they are also run on made-up files below, to show
 * they find what they should.
 */
import { existsSync, readdirSync, readFileSync } from "node:fs";
import { join, posix, relative } from "node:path";

import { describe, expect, test } from "vite-plus/test";

const root = join(import.meta.dirname, "../..");

interface SourceFile {
	/** Relative to the project root, with `/`. */
	path: string;
	source: string;
}

type ImportKind = "static" | "type" | "dynamic";

/** The modules a source file imports (`import`, `export … from`, `import()`), by kind. */
function importsOf(source: string): { specifier: string; kind: ImportKind }[] {
	const code = source.replace(/\/\*[\s\S]*?\*\//g, "").replace(/^\s*\/\/.*$/gm, "");
	const found: { specifier: string; kind: ImportKind }[] = [];
	const from = /\b(?:import|export)\s+(type\s+)?(?:[^"'`;]*?\sfrom\s+)?["']([^"']+)["']/g;
	for (const [, type, specifier] of code.matchAll(from)) {
		found.push({ specifier, kind: type ? "type" : "static" });
	}
	for (const [, specifier] of code.matchAll(/\bimport\(\s*["']([^"']+)["']\s*\)/g)) {
		found.push({ specifier, kind: "dynamic" });
	}
	return found;
}

/** The module (`src/modules/<id>`) that `specifier`, written in the file at `path`, points into. */
function moduleOf(specifier: string, path: string): string | undefined {
	if (specifier.startsWith("#modules/")) return specifier.split("/")[1];
	if (!specifier.startsWith(".")) return undefined;
	const target = posix.join(posix.dirname(path), specifier);
	return /^src\/modules\/([^/]+)\//.exec(target)?.[1];
}

const isGenerated = (file: SourceFile) =>
	/^(?:\/\/|<!--) Generated by scripts\/modules\.ts/.test(file.source);

/** Imports of a module from files outside `src/modules` (other than the generated ones). */
export function outsideImports(files: SourceFile[]): string[] {
	return files.flatMap((file) =>
		file.path.startsWith("src/modules/") || isGenerated(file)
			? []
			: importsOf(file.source).flatMap(({ specifier }) =>
					moduleOf(specifier, file.path) ? [`${file.path} imports ${specifier}`] : [],
				),
	);
}

/** Imports of one module by another. */
export function crossImports(files: SourceFile[]): string[] {
	return files.flatMap((file) => {
		const own = /^src\/modules\/([^/]+)\//.exec(file.path)?.[1];
		if (!own) return [];
		return importsOf(file.source).flatMap(({ specifier }) => {
			const target = moduleOf(specifier, file.path);
			return target && target !== own ? [`${file.path} imports ${specifier}`] : [];
		});
	});
}

/** What a `module.ts` may import statically (types and `import()` loaders are free). */
const manifestImports = [
	/^#lib\/modules\/define\.ts$/,
	/^#lib\/paraglide\/messages\.js$/,
	/^@lucide\/svelte\/icons\/[\w-]+$/,
	// Its own small scripts, e.g. `./activity.ts`, `./labels.ts`; never components or remote functions.
	/^\.\/[\w.-]+\.ts$/,
];

/** Static imports in a `module.ts` that would pull more than the manifest into every bundle. */
export function heavyManifestImports(files: SourceFile[]): string[] {
	return files
		.filter((file) => /^src\/modules\/[^/]+\/module\.ts$/.test(file.path))
		.flatMap((file) =>
			importsOf(file.source).flatMap(({ specifier, kind }) =>
				kind !== "static" ||
				(manifestImports.some((allowed) => allowed.test(specifier)) &&
					!/\.remote\./.test(specifier))
					? []
					: [`${file.path} imports ${specifier} statically: load it with import()`],
			),
		);
}

describe("the checks", () => {
	const files: SourceFile[] = [
		{
			path: "src/lib/modules/manifests.gen.ts",
			source: `// Generated by scripts/modules.ts\nimport a from "#modules/a/module.ts";`,
		},
		{
			path: "src/routes/(app)/a/+page.svelte",
			source: `<!-- Generated by scripts/modules.ts from x. -->\nimport R from "#modules/a/routes/(app)/a/+page.svelte";`,
		},
		{ path: "src/routes/(app)/orders/page.ts", source: `import { x } from "#modules/a/x.ts";` },
		{
			path: "src/lib/y.ts",
			source: `export { z } from "../modules/a/z.ts";\nconst v = await import("#modules/a/v.ts");`,
		},
		{
			path: "src/lib/ok.ts",
			source: `// import "#modules/a/commented.ts";\nimport { ok } from "./other.ts";`,
		},
		{
			path: "src/modules/a/module.ts",
			source: `
			import { defineModule } from "#lib/modules/define.ts";
			import { m } from "#lib/paraglide/messages.js";
			import Icon from "@lucide/svelte/icons/file-check";
			import type { Heavy } from "./heavy.svelte";
			import { subjects } from "./activity.ts";
			import Card from "./card.svelte";
			import { remote } from "./thing.remote.ts";
			import { server } from "#lib/server/db/index.ts";
			export default defineModule({ slots: { a: () => import("./card.svelte") } });
		`,
		},
		{
			path: "src/modules/a/x.ts",
			source: `import { b } from "#modules/b/b.ts";\nimport { own } from "#modules/a/own.ts";\nimport c from "../c/c.ts";`,
		},
	];

	test("find a module imported from outside, except by what the generator writes", () => {
		expect(outsideImports(files)).toEqual([
			`src/routes/(app)/orders/page.ts imports #modules/a/x.ts`,
			`src/lib/y.ts imports ../modules/a/z.ts`,
			`src/lib/y.ts imports #modules/a/v.ts`,
		]);
	});

	test("find a module importing another", () => {
		expect(crossImports(files)).toEqual([
			`src/modules/a/x.ts imports #modules/b/b.ts`,
			`src/modules/a/x.ts imports ../c/c.ts`,
		]);
	});

	test("find heavy static imports in a manifest, and let the rest through", () => {
		expect(heavyManifestImports(files)).toEqual([
			`src/modules/a/module.ts imports ./card.svelte statically: load it with import()`,
			`src/modules/a/module.ts imports ./thing.remote.ts statically: load it with import()`,
			`src/modules/a/module.ts imports #lib/server/db/index.ts statically: load it with import()`,
		]);
	});
});

// --- The project -----------------------------------------------------------------------------

/** The source files of the project that are checked in, leaving out what's generated or installed. */
function sourceFiles(): SourceFile[] {
	const skip = /(?:^|\/)(?:node_modules|\.svelte-kit|paraglide|build)(?:\/|$)/;
	const files: SourceFile[] = [];
	for (const folder of ["src", "e2e"]) {
		if (!existsSync(join(root, folder))) continue;
		for (const entry of readdirSync(join(root, folder), { recursive: true, withFileTypes: true })) {
			if (!entry.isFile() || !/\.(?:ts|js|svelte)$/.test(entry.name)) continue;
			const path = relative(root, join(entry.parentPath, entry.name)).replaceAll("\\", "/");
			if (skip.test(path) || path.endsWith(".gen.ts")) continue;
			files.push({ path, source: readFileSync(join(root, path), "utf8") });
		}
	}
	return files;
}

describe("the project", () => {
	const files = sourceFiles();

	test("nothing outside src/modules imports a module", () => {
		expect(outsideImports(files)).toEqual([]);
	});

	test("no module imports another", () => {
		expect(crossImports(files)).toEqual([]);
	});

	test("the manifests import nothing heavy", () => {
		expect(heavyManifestImports(files)).toEqual([]);
	});
});
