/**
 * Links the optional modules in `src/modules/<id>/` into the app. Run it with `node scripts/modules.ts`
 * (`pnpm generate` does, before `svelte-kit sync`), at the top of `vite.config.ts` (so Vite, Vitest
 * and Kit see the output) and, in dev, by `modulesPlugin()` below whenever a module's files change.
 * Everything it writes is generated and gitignored, except the module entries of `pathPattern` in
 * `project.inlang/settings.json`. It writes a file only when its content changes, so it is safe to
 * run again and again, and from several processes at once.
 *
 * For each folder with a `module.ts` it:
 *
 * - writes the registries that core reads, next to the code that reads them (`*.gen.ts`): the
 *   manifests (`src/lib/modules.gen.ts`), the plain list of ids for code that runs in plain Node
 *   (`src/lib/module-ids.gen.ts`), the server halves (`server/index.ts`, in
 *   `src/lib/server/modules.gen.ts`), the tables (`server/schema.ts`, in
 *   `src/lib/server/db/modules.gen.ts`) and the seeders (`server/seed.ts`, in
 *   `src/lib/server/db/module-seeds.gen.ts`);
 * - writes a stub in `src/routes` for every `+` file under the module's `routes/`, at the same
 *   path, so the routes are real ones (typed `./$types`, `RouteId`, layouts, endpoints, code
 *   splitting, and SvelteKit's server-only guard, which only follows files under `src/routes`).
 *   Components become a wrapper that passes its props on; scripts name their exports again, and
 *   copy the page options that are literals (`export const ssr = false`), because SvelteKit reads
 *   those without running the file, and gives up on `export * from`. Each top-level route folder it
 *   creates gets a `.gitignore` that ignores the whole folder, which is also how it knows the
 *   folder is its own and removes it when the module is gone;
 * - writes a `+layout.server.ts` at each module route root with pages that refuses the tenants
 *   without the module (`guardModule()`), then runs the module's own `+layout.server.ts` load;
 * - lists the module's message files in `pathPattern`: the core's entries first, then each module's,
 *   in id order;
 * - checks the rules and stops with the full list of what's wrong: a module's folder name is its id
 *   (`^[a-z][a-z0-9-]*$`); its route folders are plain names of their own (not a core route's, nor
 *   another module's); its message sections (`messages/<locale>/<section>.json`) are in every
 *   language and unique across the app.
 *
 * It uses no packages besides the parser of Vite+, and imports no app code, so it runs in plain Node.
 */
import {
	existsSync,
	mkdirSync,
	readdirSync,
	readFileSync,
	renameSync,
	rmSync,
	writeFileSync,
} from "node:fs";
import { dirname, join, posix, relative } from "node:path";

import { parseSync, type Plugin } from "vite-plus";

/** Starts the first line of every generated file and of the `.gitignore` in stub folders. */
const GENERATED = "Generated by scripts/modules.ts";

const MODULE_MESSAGES = "./src/modules/";
const MODULE_ID = /^[a-z][a-z0-9-]*$/;
const SECTION = /^[a-z][a-z0-9]*$/;
const ROUTE_FOLDER = /^[a-z][a-z0-9-]*$/;

// --- Finding the modules ---------------------------------------------------------------------

/** What a module's folder contains that the generator needs to know about. */
export interface ModuleFolder {
	/** The folder's name. */
	id: string;
	/** The `id:` that `module.ts` states, if it states one as a string, to check against the folder. */
	declaredId?: string;
	/** Its `+` route files, relative to `routes/`, with `/`, sorted. */
	routeFiles: string[];
	/** Which of the server files it has. */
	server: { index: boolean; schema: boolean; seed: boolean };
	/** Its message sections (`messages/<locale>/<section>.json`) per language, sorted. */
	messages: Record<string, string[]>;
}

const byName = (a: string, b: string) => (a < b ? -1 : a > b ? 1 : 0);

/** The files under `dir`, relative to it, with `/`, sorted. */
function walk(dir: string): string[] {
	if (!existsSync(dir)) return [];
	return readdirSync(dir, { recursive: true, withFileTypes: true })
		.filter((entry) => !entry.isDirectory())
		.map((entry) => posix.relative(dir.replaceAll("\\", "/"), join(entry.parentPath, entry.name)))
		.toSorted(byName);
}

/** The folders under `src/modules` with a `module.ts`, and what's wrong with the ones without. */
export function discoverModules(root: string, locales: string[]) {
	const modulesDir = join(root, "src/modules");
	const modules: ModuleFolder[] = [];
	const problems: string[] = [];
	if (!existsSync(modulesDir)) return { modules, problems };

	const folders = readdirSync(modulesDir, { withFileTypes: true })
		.filter((entry) => entry.isDirectory())
		.map((entry) => entry.name)
		.toSorted(byName);
	for (const id of folders) {
		const dir = join(modulesDir, id);
		if (!existsSync(join(dir, "module.ts"))) {
			if (readdirSync(dir).some((name) => !name.startsWith("."))) {
				problems.push(`src/modules/${id} has no module.ts, so it isn't a module.`);
			}
			continue;
		}
		if (!MODULE_ID.test(id)) {
			problems.push(`src/modules/${id}: a module's folder name is its id: ${MODULE_ID}.`);
		}
		const hasFile = (path: string) => existsSync(join(dir, path));
		const sections = (locale: string) =>
			walk(join(dir, "messages", locale))
				.filter((file) => !file.includes("/") && file.endsWith(".json"))
				.map((file) => file.slice(0, -".json".length));
		modules.push({
			id,
			declaredId: /\bid:\s*["'`]([^"'`]+)["'`]/.exec(
				readFileSync(join(dir, "module.ts"), "utf8"),
			)?.[1],
			routeFiles: walk(join(dir, "routes")).filter((file) => posix.basename(file).startsWith("+")),
			server: {
				index: hasFile("server/index.ts"),
				schema: hasFile("server/schema.ts"),
				seed: hasFile("server/seed.ts"),
			},
			messages: Object.fromEntries(locales.map((locale) => [locale, sections(locale)])),
		});
	}
	return { modules, problems };
}

// --- Route files -----------------------------------------------------------------------------

export type RouteFileKind = "page" | "layout" | "error" | "script";

/** What kind of route file `name` is (`+page.svelte`, `+layout.server.ts`, …), if it is one. */
export function routeFileKind(name: string): RouteFileKind | undefined {
	const component = /^\+(page|layout|error)(?:@[^.]*)?\.svelte$/.exec(name);
	if (component) return component[1] as RouteFileKind;
	if (/^\+(?:(?:page|layout)(?:\.server)?|server)\.[jt]s$/.test(name)) return "script";
}

/**
 * Splits a route file's path (relative to `routes/`) into its top-level route folder, which
 * includes the groups in front of it (`(app)/contracts`), and the rest (`[number]/+page.svelte`).
 * Files that sit in a group or at the root have none.
 */
export function topFolder(file: string): { folder: string; rest: string } | undefined {
	const parts = file.split("/");
	const groups = parts.findIndex((part) => !/^\(.*\)$/.test(part));
	// The file itself is the first part that's not a group: it has no folder.
	if (groups === -1 || groups === parts.length - 1) return undefined;
	return {
		folder: parts.slice(0, groups + 1).join("/"),
		rest: parts.slice(groups + 1).join("/"),
	};
}

/** The page options SvelteKit reads from a route file (and `load`), see `statically_analyse_page_options`. */
const pageOptions = new Set([
	"ssr",
	"csr",
	"prerender",
	"trailingSlash",
	"config",
	"entries",
	"load",
]);

/** What a route script exports. */
export interface RouteExports {
	/** The names of its value exports (no types). */
	names: string[];
	/** The page options it declares as literals, e.g. `{ ssr: "false" }`: name → source text. */
	literals: Record<string, string>;
}

/** The exports of a `+page.ts`, `+server.ts`, …; throws on forms the stubs can't repeat. */
export function routeExports(file: string, source: string): RouteExports {
	const { program, errors } = parseSync(file, source, { sourceType: "module" });
	if (errors.length) throw new Error(`${file}: ${errors[0].message}`);
	const names: string[] = [];
	const literals: Record<string, string> = {};
	const nameOf = (node: { type: string; name?: string; value?: unknown }) =>
		String(node.type === "Identifier" ? node.name : node.value);

	for (const statement of program.body) {
		if (statement.type === "ExportDefaultDeclaration") {
			throw new Error(`${file}: a route file can't have a default export.`);
		}
		if (statement.type === "ExportAllDeclaration") {
			throw new Error(
				`${file}: \`export * from\` hides the exports from SvelteKit's analysis: name them.`,
			);
		}
		if (statement.type !== "ExportNamedDeclaration" || statement.exportKind === "type") continue;

		const { declaration } = statement;
		if (declaration?.type === "VariableDeclaration") {
			for (const declarator of declaration.declarations) {
				if (declarator.id.type !== "Identifier") {
					throw new Error(`${file}: export names one at a time, not by destructuring.`);
				}
				const name = declarator.id.name;
				names.push(name);
				if (declaration.kind === "const" && declarator.init?.type === "Literal") {
					if (pageOptions.has(name)) {
						literals[name] = source.slice(declarator.init.start, declarator.init.end);
					}
				}
			}
		} else if (
			(declaration?.type === "FunctionDeclaration" || declaration?.type === "ClassDeclaration") &&
			declaration.id
		) {
			names.push(declaration.id.name);
		}
		for (const specifier of statement.specifiers) {
			if (specifier.exportKind !== "type") names.push(nameOf(specifier.exported));
		}
	}
	return { names, literals };
}

const generatedBy = (from: string) => `${GENERATED} from ${from}. Don't edit.`;

/** A name for an import in a stub: `load` → `moduleLoad`. */
const moduleName = (name: string) => `module${name[0].toUpperCase()}${name.slice(1)}`;

/**
 * A stub for a `+page.ts`, `+server.ts`, … that gives Kit the module's exports under the same
 * names: page options that are literals are repeated (Kit then needs no more than the stub to know
 * them), the rest is re-exported. With `guard`, it's the `+layout.server.ts` of a module's route
 * root: it refuses the tenants without the module, then runs the module's `load` if it has one.
 */
export function renderScriptStub(options: {
	/** The module's file, for the header. */
	from: string;
	/** How the stub imports it. */
	importPath: string;
	exports: RouteExports;
	/** The id of the module to guard for. */
	guard?: string;
}): string {
	const { from, importPath, exports, guard } = options;
	const { names, literals } = exports;
	const viaConst = names.filter(
		(name) => pageOptions.has(name) && !(name in literals) && !(guard && name === "load"),
	);
	const reexported = names.filter((name) => !pageOptions.has(name));
	const hasLoad = names.includes("load");

	const head: string[] = [];
	const body: string[] = [];
	if (guard) {
		head.push(`import type { LayoutServerLoadEvent } from "./$types";`, "");
		head.push(`import { guardModule } from "#lib/server/modules.ts";`);
	}
	const imported = [...viaConst, ...(guard && hasLoad ? ["load"] : [])];
	if (imported.length) {
		const specifiers = imported.map((name) => `${name} as ${moduleName(name)}`).join(", ");
		head.push(`import { ${specifiers} } from "${importPath}";`);
	}

	for (const [name, text] of Object.entries(literals)) body.push(`export const ${name} = ${text};`);
	for (const name of viaConst) body.push(`export const ${name} = ${moduleName(name)};`);
	if (reexported.length) body.push(`export { ${reexported.join(", ")} } from "${importPath}";`);
	if (guard) {
		const call = `guardModule(${JSON.stringify(guard)});`;
		body.push(
			hasLoad
				? `export const load = async (event: LayoutServerLoadEvent) => {\n\t${call}\n\t// Whatever the module's load takes of the event is checked here; one that takes none is fine.\n\tconst run: (event: LayoutServerLoadEvent) => ReturnType<typeof moduleLoad> = moduleLoad;\n\treturn run(event);\n};`
				: `export const load = () => {\n\t${call}\n};`,
		);
	}
	return [`// ${generatedBy(from)}`, ...(head.length ? ["", ...head] : []), "", ...body, ""].join(
		"\n",
	);
}

/**
 * A stub for a `+page.svelte`, `+layout.svelte` or `+error.svelte`: it passes its props on. A layout
 * renders its `children` inside the module's layout itself, because Kit warns about a layout that
 * doesn't (it looks for the `{@render}` in the source).
 */
export function renderComponentStub(options: {
	from: string;
	importPath: string;
	kind: "page" | "layout" | "error";
}): string {
	const { from, importPath, kind } = options;
	const props = { page: "PageProps", layout: "LayoutProps", error: undefined }[kind];
	return [
		`<!-- ${generatedBy(from)} -->`,
		`<script lang="ts">`,
		...(props ? [`\timport type { ${props} } from "./$types";`, ""] : []),
		`\timport Route from "${importPath}";`,
		...(kind === "layout" ? ["", `\tlet { children, ...props }: LayoutProps = $props();`] : []),
		...(kind === "page" ? ["", `\tlet props: PageProps = $props();`] : []),
		`</script>`,
		"",
		kind === "layout"
			? `<Route {...props}>{@render children()}</Route>`
			: props
				? `<Route {...props} />`
				: `<Route />`,
		"",
	].join("\n");
}

// --- The registries --------------------------------------------------------------------------

const camel = (id: string) => id.replace(/-(\w)/g, (_, c: string) => c.toUpperCase());

const registryHeader = (what: string) => `// ${GENERATED} from ${what}. Don't edit.\n`;

/** The generated registries, by path relative to the project root. */
export function renderRegistries(modules: ModuleFolder[]): Record<string, string> {
	const withServer = modules.filter((module) => module.server.index);
	const withSchema = modules.filter((module) => module.server.schema);
	const withSeed = modules.filter((module) => module.server.seed);
	const list = (names: string[]) => `[${names.join(", ")}]`;

	return {
		"src/lib/module-ids.gen.ts": [
			registryHeader("src/modules/*/module.ts"),
			`/** The ids of the modules in \`src/modules\`, for code that can't import their manifests. */`,
			`export const generatedModuleIds = ${list(modules.map((m) => JSON.stringify(m.id)))} as const;`,
			"",
		].join("\n"),

		"src/lib/modules.gen.ts": [
			registryHeader("src/modules/*/module.ts"),
			...modules.map((m) => `import ${camel(m.id)}Module from "#modules/${m.id}/module.ts";`),
			...(modules.length ? [""] : []),
			`export const manifests = ${list(modules.map((m) => `${camel(m.id)}Module`))} as const;`,
			"",
		].join("\n"),

		"src/lib/server/modules.gen.ts": [
			registryHeader("src/modules/*/server/index.ts"),
			...withServer.map(
				(m) => `import ${camel(m.id)}Server from "#modules/${m.id}/server/index.ts";`,
			),
			...(withServer.length ? [""] : []),
			`/**`,
			` * A function, not a constant: the modules import \`defineServerModule()\` from`,
			` * \`#lib/server/modules.ts\`, which imports this, so one of them is always evaluated first.`,
			` */`,
			`export function generatedServerModules() {`,
			`\treturn ${list(withServer.map((m) => `${camel(m.id)}Server`))} as const;`,
			`}`,
			"",
		].join("\n"),

		"src/lib/server/db/modules.gen.ts": [
			registryHeader("src/modules/*/server/schema.ts"),
			...(withSchema.length
				? withSchema.map((m) => `export * from "#modules/${m.id}/server/schema.ts";`)
				: ["export {};"]),
			"",
		].join("\n"),

		"src/lib/server/db/module-seeds.gen.ts": [
			registryHeader("src/modules/*/server/seed.ts"),
			`import type { ModuleSeed } from "./seed/module-seed.ts";`,
			...withSeed.map((m) => `import ${camel(m.id)}Seed from "#modules/${m.id}/server/seed.ts";`),
			"",
			`export const moduleSeeds: { id: string; seed: ModuleSeed }[] = ${
				withSeed.length
					? `[\n${withSeed.map((m) => `\t{ id: ${JSON.stringify(m.id)}, seed: ${camel(m.id)}Seed },`).join("\n")}\n]`
					: "[]"
			};`,
			"",
		].join("\n"),
	};
}

// --- Messages --------------------------------------------------------------------------------

/** The message sections of a module, e.g. `["contracts"]` (those of its first language). */
const sectionsOf = (module: ModuleFolder) => Object.values(module.messages)[0] ?? [];

/** The inlang `pathPattern`: the core's entries as they were, then each module's, in id order. */
export function renderPathPattern(existing: string[], modules: ModuleFolder[]): string[] {
	return [
		...existing.filter((pattern) => !pattern.startsWith(MODULE_MESSAGES)),
		...modules.flatMap((module) =>
			sectionsOf(module).map(
				(section) => `${MODULE_MESSAGES}${module.id}/messages/{locale}/${section}.json`,
			),
		),
	];
}

/** `settings.json`'s text with `pathPattern` replaced, leaving the rest of the file as it is. */
export function replacePathPattern(settings: string, patterns: string[]): string {
	const pattern = /^(\t*)"pathPattern": \[[^\]]*\]/m;
	const match = pattern.exec(settings);
	if (!match) throw new Error(`project.inlang/settings.json has no "pathPattern" list.`);
	const indent = match[1];
	const entries = patterns.map((entry) => `${indent}\t${JSON.stringify(entry)}`).join(",\n");
	return settings.replace(pattern, () => `${indent}"pathPattern": [\n${entries}\n${indent}]`);
}

// --- The rules -------------------------------------------------------------------------------

const isGroup = (name: string) => /^\(.*\)$/.test(name);

function hasMarker(dir: string) {
	const file = join(dir, ".gitignore");
	return existsSync(file) && readFileSync(file, "utf8").startsWith(`# ${GENERATED}`);
}

/**
 * The top-level route folders under `src/routes` (`(app)/orders`, `login`: those under groups
 * count as top-level), split into the ones the generator made and the core's own.
 */
export function scanRoutes(root: string) {
	const stubs: string[] = [];
	const core: string[] = [];
	const visit = (relativeDir: string) => {
		const dir = join(root, "src/routes", relativeDir);
		if (!existsSync(dir)) return;
		for (const entry of readdirSync(dir, { withFileTypes: true })) {
			if (!entry.isDirectory()) continue;
			const path = posix.join(relativeDir, entry.name);
			if (hasMarker(join(dir, entry.name))) stubs.push(path);
			else if (isGroup(entry.name)) visit(path);
			else core.push(path);
		}
	};
	visit("");
	return { stubs: stubs.toSorted(byName), core: core.toSorted(byName) };
}

/** What breaks the rules, as sentences; nothing when the modules are fine. */
export function checkModules(
	modules: ModuleFolder[],
	options: { coreRouteFolders: string[]; patterns: string[]; locales: string[] },
): string[] {
	const problems: string[] = [];
	const coreSegments = new Set(options.coreRouteFolders.map((folder) => posix.basename(folder)));
	/** The module that has a route segment, to refuse a second one. */
	const segmentOwner = new Map<string, string>();
	const sectionOwner = new Map<string, string>();
	for (const pattern of options.patterns) {
		const section = /^\.\/messages\/\{locale\}\/([\w-]+)\.json$/.exec(pattern)?.[1];
		if (section) sectionOwner.set(section, "the core");
	}

	for (const module of modules) {
		const where = `src/modules/${module.id}`;

		for (const file of module.routeFiles) {
			if (!routeFileKind(posix.basename(file))) {
				problems.push(`${where}/routes/${file} isn't a route file SvelteKit knows.`);
				continue;
			}
			const split = topFolder(file);
			if (!split) {
				problems.push(
					`${where}/routes/${file} is outside a route folder of its own: a module's routes live in ` +
						`folders it names itself (e.g. routes/(app)/${module.id}/…), never in the core's.`,
				);
				continue;
			}
			const segment = posix.basename(split.folder);
			if (!ROUTE_FOLDER.test(segment)) {
				problems.push(
					`${where}/routes/${split.folder}: a module's route folder is a plain name (${ROUTE_FOLDER}).`,
				);
			} else if (coreSegments.has(segment)) {
				problems.push(
					`${where}/routes/${split.folder} collides with the core's /${segment} route.`,
				);
			} else if (segmentOwner.get(segment) && segmentOwner.get(segment) !== module.id) {
				problems.push(
					`${where}/routes/${split.folder} collides with the /${segment} route of the ${segmentOwner.get(segment)} module.`,
				);
			} else {
				segmentOwner.set(segment, module.id);
			}
		}

		const [first, ...others] = options.locales;
		for (const locale of others) {
			const have = module.messages[locale] ?? [];
			const expected = module.messages[first] ?? [];
			for (const section of expected.filter((s) => !have.includes(s))) {
				problems.push(`${where}/messages/${locale}/${section}.json is missing (${first} has it).`);
			}
			for (const section of have.filter((s) => !expected.includes(s))) {
				problems.push(`${where}/messages/${first}/${section}.json is missing (${locale} has it).`);
			}
		}
		for (const section of sectionsOf(module)) {
			if (!SECTION.test(section)) {
				problems.push(`${where}/messages: the section name "${section}" must match ${SECTION}.`);
			} else if (sectionOwner.has(section)) {
				problems.push(
					`${where}/messages: the section "${section}" is also ${sectionOwner.get(section)}'s: keys start with the section's name, so it must be unique.`,
				);
			} else {
				sectionOwner.set(section, `the ${module.id} module`);
			}
		}

		if (module.declaredId && module.declaredId !== module.id) {
			problems.push(
				`${where}/module.ts: its id is "${module.declaredId}", but the folder is "${module.id}".`,
			);
		}
	}
	return problems;
}

// --- Route stubs -----------------------------------------------------------------------------

const gitignore = `# ${GENERATED}, and deleted by it when the module goes. Don't edit.\n*\n`;

/**
 * The stubs for the modules' routes, per top-level route folder under `src/routes` (e.g.
 * `(app)/contracts`): the files in it, relative to it, with their content.
 */
export function planStubs(root: string, modules: ModuleFolder[]): Map<string, Map<string, string>> {
	const folders = new Map<string, Map<string, string>>();
	for (const module of modules) {
		const files = module.routeFiles.flatMap((file) => {
			const split = topFolder(file);
			return split ? [{ file, name: posix.basename(file), ...split }] : [];
		});
		/** The route folders with a page, which get the guard (unless the module has its own). */
		const withPages = new Set(
			files.filter(({ name }) => routeFileKind(name) === "page").map(({ folder }) => folder),
		);
		const ownGuards = new Set(
			files
				.filter(({ rest }) => /^\+layout\.server\.[jt]s$/.test(rest))
				.map(({ folder }) => folder),
		);

		for (const { file, name, folder, rest } of files) {
			const kind = routeFileKind(name)!;
			const from = `src/modules/${module.id}/routes/${file}`;
			const importPath = posix.relative(posix.dirname(`src/routes/${file}`), from);
			const stub =
				kind === "script"
					? renderScriptStub({
							from,
							importPath,
							exports: routeExports(from, readFileSync(join(root, from), "utf8")),
							guard: /^\+layout\.server\.[jt]s$/.test(rest) ? module.id : undefined,
						})
					: renderComponentStub({ from, importPath, kind });
			const stubs = folders.get(folder) ?? new Map([[".gitignore", gitignore]]);
			folders.set(folder, stubs.set(rest, stub));
		}
		for (const folder of withPages) {
			if (ownGuards.has(folder)) continue;
			folders.get(folder)!.set(
				"+layout.server.ts",
				renderScriptStub({
					from: `the ${module.id} module`,
					importPath: "",
					exports: { names: [], literals: {} },
					guard: module.id,
				}),
			);
		}
	}
	return folders;
}

// --- Writing ---------------------------------------------------------------------------------

/** Writes `file` unless it already has this content; through a rename, so readers never see half. */
function writeIfChanged(file: string, content: string) {
	if (existsSync(file) && readFileSync(file, "utf8") === content) return false;
	mkdirSync(dirname(file), { recursive: true });
	const temporary = `${file}.${process.pid}.tmp`;
	writeFileSync(temporary, content);
	renameSync(temporary, file);
	return true;
}

/** Makes `dir` hold exactly the `wanted` files (relative paths → content); returns what changed. */
function syncFolder(dir: string, wanted: Map<string, string>) {
	const changed: string[] = [];
	for (const file of walk(dir)) {
		if (wanted.has(file)) continue;
		rmSync(join(dir, file), { force: true });
		changed.push(join(dir, file));
	}
	for (const [file, content] of wanted) {
		if (writeIfChanged(join(dir, file), content)) changed.push(join(dir, file));
	}
	// The folders of files that are gone, deepest first.
	const folders = existsSync(dir)
		? readdirSync(dir, { recursive: true, withFileTypes: true }).filter((entry) =>
				entry.isDirectory(),
			)
		: [];
	for (const folder of folders.toSorted((a, b) => b.parentPath.length - a.parentPath.length)) {
		const path = join(folder.parentPath, folder.name);
		if (existsSync(path) && !readdirSync(path).length) rmSync(path, { recursive: true });
	}
	return changed;
}

/**
 * Brings everything the generator writes in line with the modules in `src/modules`. Throws, listing
 * every problem, when they break the rules. Returns the modules' ids and the files it wrote.
 */
export function generateModules(root: string) {
	const settingsFile = join(root, "project.inlang/settings.json");
	const settingsText = readFileSync(settingsFile, "utf8");
	const settings = JSON.parse(settingsText);
	const locales: string[] = settings.locales;
	const patterns: string[] = settings["plugin.inlang.messageFormat"].pathPattern;

	const { modules, problems } = discoverModules(root, locales);
	const routes = scanRoutes(root);
	problems.push(...checkModules(modules, { coreRouteFolders: routes.core, patterns, locales }));
	if (problems.length) {
		throw new Error(`The modules in src/modules break the rules:\n- ${problems.join("\n- ")}`);
	}

	const changed: string[] = [];
	const write = (path: string, content: string) => {
		if (writeIfChanged(join(root, path), content)) changed.push(path);
	};
	for (const [path, content] of Object.entries(renderRegistries(modules))) write(path, content);
	write(
		"project.inlang/settings.json",
		replacePathPattern(settingsText, renderPathPattern(patterns, modules)),
	);

	const stubs = planStubs(root, modules);
	for (const folder of routes.stubs.filter((folder) => !stubs.has(folder))) {
		rmSync(join(root, "src/routes", folder), { recursive: true, force: true });
		changed.push(`src/routes/${folder}`);
	}
	for (const [folder, files] of stubs) {
		const dir = join(root, "src/routes", folder);
		changed.push(...syncFolder(dir, files).map((file) => relative(root, file)));
	}
	return { modules: modules.map((module) => module.id), changed };
}

// --- Dev server ------------------------------------------------------------------------------

/** The files whose coming and going changes what the generator writes. */
const inputs =
	/^src\/modules(?:\/[^/]+(?:\/(?:module\.ts|routes(?:\/.*)?|server(?:\/(?:index|schema|seed)\.ts)?|messages(?:\/.*)?))?)?$/;

/** Reruns the generator in dev when a module's files come, go or (for route scripts) change. */
export function modulesPlugin(root: string): Plugin {
	return {
		name: "modules",
		configureServer({ watcher, config }) {
			let timer: ReturnType<typeof setTimeout> | undefined;
			const regenerate = () => {
				clearTimeout(timer);
				timer = setTimeout(() => {
					try {
						generateModules(root);
					} catch (error) {
						config.logger.error((error as Error).message);
					}
				}, 50);
			};
			const watch = (event: string) => (file: string) => {
				const path = relative(root, file).replaceAll("\\", "/");
				if (!inputs.test(path)) return;
				// A change in a route script may add or drop a page option or an export.
				if (event === "change" && !/\/routes\/.*\+[^/]*\.[jt]s$/.test(path)) return;
				regenerate();
			};
			for (const event of ["add", "addDir", "unlink", "unlinkDir", "change"]) {
				watcher.on(event, watch(event));
			}
		},
	};
}

if (import.meta.main) {
	const { modules, changed } = generateModules(process.cwd());
	if (changed.length) {
		console.log(`Linked ${modules.length} modules (${changed.length} files written).`);
	}
}
