import { describe, expect, test } from "vite-plus/test";

import { routeExports } from "./routes.ts";
import { renderComponentStub, renderGroupGuard, renderScriptStub } from "./stubs.ts";

describe("renderScriptStub", () => {
	const importPath = "#modules/sample/routes/sample/+page.ts";

	test("repeats literal page options and names the other exports", () => {
		const exports = routeExports(
			"+page.ts",
			`export const prerender = true; export const load = () => ({}); export const config = {};`,
		);
		expect(
			renderScriptStub({ from: "src/modules/sample/routes/sample/+page.ts", importPath, exports }),
		)
			.toBe(`// Generated by scripts/modules.ts from src/modules/sample/routes/sample/+page.ts. Don't edit.

import { load as moduleLoad, config as moduleConfig } from "${importPath}";

export const prerender = true;
export const load = moduleLoad;
export const config = moduleConfig;
`);
	});

	test("re-exports endpoints", () => {
		const exports = routeExports(
			"+server.ts",
			`export const GET = () => {}; export const POST = 1;`,
		);
		const stub = renderScriptStub({ from: "x/+server.ts", importPath, exports });
		expect(stub).toContain(`export { GET, POST } from "${importPath}";`);
		expect(stub).not.toContain("import {");
	});

	test("guards a server page's load and actions, typed by the route", () => {
		const exports = routeExports(
			"+page.server.ts",
			`export const ssr = false; export const load = () => ({}); export const actions = {};`,
		);
		const stub = renderScriptStub({
			from: "x/+page.server.ts",
			importPath,
			exports,
			guard: { id: "sample", kind: "page" },
		});
		expect(stub).toBe(`// Generated by scripts/modules.ts from x/+page.server.ts. Don't edit.

import type { PageServerLoadEvent, Actions } from "./$types";

import { guarded, guardedActions } from "#lib/server/modules/hooks.ts";
import { load as moduleLoad, actions as moduleActions } from "${importPath}";

export const ssr = false;
export const load = guarded<PageServerLoadEvent, ReturnType<typeof moduleLoad>>("sample", moduleLoad);
export const actions = guardedActions("sample", moduleActions satisfies Actions);
`);
	});

	test("guards a server layout's load", () => {
		const exports = routeExports("+layout.server.ts", `export const load = () => ({ a: 1 });`);
		const stub = renderScriptStub({
			from: "x/+layout.server.ts",
			importPath,
			exports,
			guard: { id: "sample", kind: "layout" },
		});
		expect(stub).toContain(`import type { LayoutServerLoadEvent } from "./$types";`);
		expect(stub).toContain(
			`export const load = guarded<LayoutServerLoadEvent, ReturnType<typeof moduleLoad>>("sample", moduleLoad);`,
		);
	});

	test("guards each request handler of an endpoint, and nothing else", () => {
		const exports = routeExports(
			"+server.ts",
			`export const GET = () => {}; export function POST() {}; export const prerender = false; export const config = {};`,
		);
		const stub = renderScriptStub({
			from: "x/+server.ts",
			importPath,
			exports,
			guard: { id: "sample", kind: "endpoint" },
		});
		expect(stub).toContain(`import type { RequestEvent } from "./$types";`);
		expect(stub).toContain(
			`import { config as moduleConfig, GET as moduleGET, POST as modulePOST } from "${importPath}";`,
		);
		expect(stub).toContain(
			`export const GET = guarded<RequestEvent, ReturnType<typeof moduleGET>>("sample", moduleGET);`,
		);
		expect(stub).toContain(
			`export const POST = guarded<RequestEvent, ReturnType<typeof modulePOST>>("sample", modulePOST);`,
		);
		expect(stub).toContain("export const prerender = false;");
		expect(stub).toContain("export const config = moduleConfig;");
	});

	test("guards nothing in a server file that answers no request", () => {
		const exports = routeExports("+page.server.ts", `export const prerender = true;`);
		const stub = renderScriptStub({
			from: "x/+page.server.ts",
			importPath,
			exports,
			guard: { id: "sample", kind: "page" },
		});
		expect(stub).not.toContain("import");
		expect(stub).toContain("export const prerender = true;");
	});
});

describe("renderGroupGuard", () => {
	test("guards each route folder of the group for its module", () => {
		const stub = renderGroupGuard(
			new Map([
				["/(app)/(modules)/sample", "sample"],
				["/(app)/(modules)/other", "other-module"],
			]),
		);
		expect(stub).toContain(`import { guardModuleRoute } from "#lib/server/modules/hooks.ts";`);
		expect(stub).toContain(
			`const owners = {\n\t"/(app)/(modules)/sample": "sample",\n\t"/(app)/(modules)/other": "other-module",\n} as const;`,
		);
		expect(stub).toContain(
			`export const load = ({ route }: LayoutServerLoadEvent) => {\n\tguardModuleRoute(route.id, owners);\n};`,
		);
	});
});

describe("renderComponentStub", () => {
	test("passes the props of a page or layout on, typed by the route", () => {
		const stub = renderComponentStub({
			from: "x/+page.svelte",
			importPath: "#modules/x/+page.svelte",
			kind: "page",
		});
		expect(stub).toContain(`import type { PageProps } from "./$types";`);
		expect(stub).toContain(`let props: PageProps = $props();`);
		expect(stub).toContain(`<Route {...props} />`);
		expect(renderComponentStub({ from: "x", importPath: "y.svelte", kind: "layout" })).toContain(
			"LayoutProps",
		);
	});

	test("takes no props for an error page", () => {
		const stub = renderComponentStub({ from: "x", importPath: "y.svelte", kind: "error" });
		expect(stub).toContain("<Route />");
		expect(stub).not.toContain("$types");
	});
});
