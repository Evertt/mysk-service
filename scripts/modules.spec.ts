describe("routeFileKind", () => {
	test.each([
		["+page.svelte", "page"],
		["+page@(app).svelte", "page"],
		["+layout.svelte", "layout"],
		["+layout@.svelte", "layout"],
		["+error.svelte", "error"],
		["+page.ts", "script"],
		["+page.server.ts", "script"],
		["+layout.ts", "script"],
		["+layout.server.js", "script"],
		["+server.ts", "script"],
	])("%s is a %s", (name, kind) => {
		expect(routeFileKind(name)).toBe(kind);
	});

	test.each(["+foo.svelte", "+page.svelte.ts", "page.svelte", "+hooks.ts", "+page.server.svelte"])(
		"%s is not a route file",
		(name) => {
			expect(routeFileKind(name)).toBeUndefined();
		},
	);
});

describe("topFolder", () => {
	test("is the first folder that isn't a group, with the groups before it", () => {
		expect(topFolder("(app)/contracts/[number]/+page.svelte")).toEqual({
			folder: "(app)/contracts",
			rest: "[number]/+page.svelte",
		});
		expect(topFolder("(app)/(inner)/contracts/+layout.svelte")).toEqual({
			folder: "(app)/(inner)/contracts",
			rest: "+layout.svelte",
		});
		expect(topFolder("reports/+page.ts")).toEqual({ folder: "reports", rest: "+page.ts" });
	});

	test("is nothing for a file that sits in a group or at the root", () => {
		expect(topFolder("(app)/+page.svelte")).toBeUndefined();
		expect(topFolder("+layout.svelte")).toBeUndefined();
	});
});

describe("routeExports", () => {
	test("lists the value exports, and the page options that are literals", () => {
		const source = `
			import type { PageLoad } from "./$types";
			export const prerender = true;
			export const trailingSlash = "always";
			export const ssr = ssrFlag;
			export const load: PageLoad = () => ({});
			export async function GET() {}
			const a = 1, b = 2;
			export { a, b as c };
			export type Thing = string;
			export interface Other {}
			export type { Other as Another };
		`;
		expect(routeExports("+page.ts", source)).toEqual({
			names: ["prerender", "trailingSlash", "ssr", "load", "GET", "a", "c"],
			literals: { prerender: "true", trailingSlash: '"always"' },
		});
	});

	test("refuses what a stub can't repeat", () => {
		expect(() => routeExports("+page.ts", `export * from "./other.ts";`)).toThrow(/export \* from/);
		expect(() => routeExports("+page.ts", `export default 1;`)).toThrow(/default export/);
		expect(() => routeExports("+page.ts", `export const { a } = x;`)).toThrow(/destructuring/);
		expect(() => routeExports("+page.ts", `export const = ;`)).toThrow(/\+page\.ts/);
	});
});

describe("renderScriptStub", () => {
	const importPath = "../../modules/sample/routes/sample/+page.ts";

	test("repeats literal page options and names the other exports", () => {
		const exports = routeExports(
			"+page.ts",
			`export const prerender = true; export const load = () => ({}); export const config = {};`,
		);
		expect(
			renderScriptStub({ from: "src/modules/sample/routes/sample/+page.ts", importPath, exports }),
		)
			.toBe(`// Generated by scripts/modules.ts from src/modules/sample/routes/sample/+page.ts. Don't edit.

import { load as moduleLoad, config as moduleConfig } from "${importPath}";

export const prerender = true;
export const load = moduleLoad;
export const config = moduleConfig;
`);
	});

	test("re-exports endpoints", () => {
		const exports = routeExports(
			"+server.ts",
			`export const GET = () => {}; export const POST = 1;`,
		);
		const stub = renderScriptStub({ from: "x/+server.ts", importPath, exports });
		expect(stub).toContain(`export { GET, POST } from "${importPath}";`);
		expect(stub).not.toContain("import {");
	});

	test("guards a route root's layout, then runs the module's load", () => {
		const exports = routeExports("+layout.server.ts", `export const load = () => ({ a: 1 });`);
		const stub = renderScriptStub({
			from: "x/+layout.server.ts",
			importPath,
			exports,
			guard: "sample",
		});
		expect(stub).toContain(`import { guardModule } from "#lib/server/modules.ts";`);
		expect(stub).toContain(`import { load as moduleLoad } from "${importPath}";`);
		expect(stub).toContain(`guardModule("sample");\n\treturn moduleLoad(event);`);
		// Kit reads that there is a `load`, and no more.
		expect(stub).toContain("export const load = async (event: LayoutServerLoadEvent) => {");
	});

	test("only guards when the module has no load of its own", () => {
		const stub = renderScriptStub({
			from: "the sample module",
			importPath: "",
			exports: { names: [], literals: {} },
			guard: "sample",
		});
		expect(stub).toContain(`export const load = () => {\n\tguardModule("sample");\n};`);
		expect(stub).not.toContain("moduleLoad");
	});
});

